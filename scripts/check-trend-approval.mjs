import assert from 'node:assert/strict';
import { newsEntries, publishedNews, contentDigest } from '../src/data/news.js';
import { trendSnapshots } from '../src/data/trendSnapshots.js';
import { approvedTrendSnapshots, snapshotDigest } from '../src/data/trends.js';
const clone = value => structuredClone(value);
const approveArticle = e => ({ ...e, approval: { ...e.approval, contentDigest: contentDigest(e) } });
const approveSnapshot = s => ({ ...s, approval: { ...s.approval, contentDigest: snapshotDigest(s) } });
assert.equal(approvedTrendSnapshots().length, trendSnapshots.length);
const edited = clone(newsEntries); edited[0].title += ' changed';
assert.throws(() => publishedNews(edited), /unapproved/);
edited[0] = approveArticle(edited[0]);
assert.throws(() => approvedTrendSnapshots(trendSnapshots, edited), /Stale/);
assert.throws(() => approvedTrendSnapshots(trendSnapshots, newsEntries.slice(1)));
const addition = approveArticle({ ...clone(newsEntries[0]), id: 999, slug: 'new-article' });
assert.throws(() => approvedTrendSnapshots(trendSnapshots, [...newsEntries, addition]), /Stale/);
const altered = clone(trendSnapshots); altered[0].thesis += ' changed';
assert.throws(() => approvedTrendSnapshots(altered), /unapproved/);
assert.throws(() => approvedTrendSnapshots([]), /review required/);
const renewed = approveSnapshot({ ...clone(trendSnapshots[0]), id: '2026-asof-20260918-r3', asOf: '2026-09-18', entryDigests: edited.map(contentDigest) });
const history = approvedTrendSnapshots([...trendSnapshots, renewed], edited);
assert.equal(history.length, trendSnapshots.length + 1);
assert.deepEqual(history[0], trendSnapshots[0]);
assert.throws(() => approvedTrendSnapshots([...trendSnapshots, trendSnapshots[0]]), /unapproved/);
console.log('PASS exact-copy approval, changed/added/removed news stale guard, unapproved analysis, append-only historical snapshot retention');
